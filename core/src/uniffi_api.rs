        assert!(matches!(e, YubtcError::Invalid(_)));
        let e: YubtcError = MsError::NotAParticipant.into();
        assert!(matches!(e, YubtcError::Invalid(_)));

        // MsSendError delegates arm-by-arm to the standalone mappings.
        let e: YubtcError = MsSendError::Ms(MsError::ForeignWif).into();
