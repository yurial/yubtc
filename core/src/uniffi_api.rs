//! UniFFI bindings: a sync facade over the async wallet core.
//!
//! UniFFI's foreign-function surface is synchronous. The internal
//! wallet and network APIs are async because they call `reqwest`; we
//! bridge that by running the async work on a process-wide tokio
//! runtime installed lazily on first use. Callers (Kotlin, Swift,
//! Python) get plain methods and never see a runtime handle.
//!
//! # Why a custom facade
//!
//! The wallet's real types (`SigningKey`, `[u8; 32]`, raw
//! `Transaction`, `Arc<dyn NetworkBackend>`, ...) are not foreign-
//! function safe. Wrapping them in UniFFI records / objects forces a
//! clean conversion at the FFI boundary:
//!
//! - Keys are kept inside an opaque `WalletHandle`; only addresses,
//!   WIFs, raw tx hex, and human-readable amounts cross the boundary.
//! - `Result<T, WalletError>` becomes `Result<T, YubtcError>` with the
//!   variant names spelled out — the foreign side never sees a Rust
//!   error type by name.
//! - Backend selection is by name (`"blockchain.info"` /
//!   `"blockstream"` / `"mempool.space"`); no `Arc` crosses.
//!
//! # Synchronous network
//!
//! The wallet's network methods (`address_info`, `unspent`,
//! `make_transaction`, `broadcast`) call out to `reqwest`. They block
//! on a tokio runtime, so the FFI surface stays sync without dropping
//! the connection-pooling and timeout that `reqwest` gives us.
//!
//! # Re-exports
//!
//! This module is the single source of truth for the UniFFI surface.
//! `lib.rs` calls `uniffi::setup_scaffolding!()` exactly once.
//!
//! # Built artifacts
//!
//! `yubtc-core` produces a `cdylib` named `libyubtc_core.so` (Linux /
//! Android) / `libyubtc_core.dylib` (macOS) / `libyubtc_core.dll`
//! (Windows) / `libyubtc_core.a` (static). Foreign-language facades are
//! generated by `uniffi-bindgen` from the cdylib's embedded metadata:
//!
//! - Kotlin — [`../../../bindings/kotlin/uniffi/yubtc_core/yubtc_core.kt`].
//! - Swift, Python, Ruby — generated on demand via `uniffi-bindgen
//!   generate --language <LANG>` (not yet produced for this repo).
//!
//! Android ABI cross-compilation (arm64-v8a / armeabi-v7a / x86_64) is
//! driven by [`.github/workflows/release.yml`](../../../.github/workflows/release.yml).

