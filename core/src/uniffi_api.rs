impl From<MsFormName> for wallet::MsForm {
    fn from(f: MsFormName) -> Self {
        match f {
            MsFormName::P2sh => wallet::MsForm::P2sh,
            MsFormName::P2wsh => wallet::MsForm::P2wsh,
            MsFormName::P2tr => wallet::MsForm::P2tr,
        }
    }
}

// --- Objects ---------------------------------------------------------

/// Foreign-facing handle to a wallet.
///
/// The handle owns the `(seed, passphrase, kdf)` tuple so the scan
/// methods ([`Self::all_unspent`] and [`Self::select_inputs_until`])
/// can derive any address on demand. The actual `(privkey, UTXO)`
/// tuples produced by the most recent scan live behind an internal
/// `Mutex<Option<...>>` and are evicted when the user calls
/// [`Self::lock`] or [`uniffi::set_backend`] swaps the active
/// provider.
///
/// **Stateless by design.** No seed material is written to disk;
/// the handle is the only carrier of the secret and the wallet's
/// on-chain view. Closing the app or wiping the handle destroys
/// the secret in memory (Rust's `Drop` for the inner `TSeed`/
/// `TPassphrase`).
// No `Debug` derive: the backend field is `Arc<dyn NetworkBackend>`
// (not `Debug`), and a derived impl could print secret material in
// diagnostics anyway.
#[derive(uniffi::Object)]
pub struct WalletHandle {
    seed: TSeed,
    passphrase: TPassphrase,
    kdf: KdfAlgo,
    /// Receive-address form of this handle's keys (specs/spec.md
    /// «Адресная политика»: the type affects only receiving/cashback —
    /// the scan always sees every form). Stateless per invocation:
    /// derived addresses follow this type, UTXOs of all forms are
    /// visible regardless.
    addr_type: wallet::AddrType,
    /// Network backend this handle talks to — resolved once at
    /// construction from the `backend` name (default
    /// blockchain.info), swappable via `Self::set_backend`. No
    /// process-global backend exists (specs/spec.md «Явная передача
    /// бэкенда»). `RwLock` because UniFFI methods take `&self`.
    backend: std::sync::RwLock<std::sync::Arc<dyn net::NetworkBackend>>,
    /// Cached scan output, populated by `all_unspent` /
    /// `select_inputs_until`. Evicted on `lock()`.
    cache: Mutex<Option<ScanCache>>,
}

/// Per-address data cached by a scan.
#[derive(Debug, Clone)]
struct ScanCache {
    /// Per-`(nonce, form)` `(address, privkey, UTXOs)` collected
    /// during the last scan, in scan order (nonce ascending, forms in
    /// P2PKH → P2WPKH → P2TR order within a nonce). Preserves scan
    /// order so callers can compute "last sourced address" /
    /// "gap-limit unused address" if they need them.
    entries: Vec<CacheEntry>,
    /// Address to use for cashback when none is supplied to
    /// [`WalletHandle::make_transaction_multi`]. Set by the scan
    /// to the gap-limit unused address (eager scan) or to the
    /// last sourced address (lazy scan with target-met). Already
    /// encoded in the receiving form (gap stop) or the last source's
    /// form (target-met).
    cashback_addr: TAddress,
}

#[derive(Debug, Clone)]
#[allow(dead_code)] // `address` / `privkey` are part of the cache state and may be exposed by future methods.
struct CacheEntry {
    nonce: u32,
    /// The form this entry's address/key belongs to.
    addr_type: wallet::AddrType,
    address: TAddress,
    privkey: TPrivKey,
    unspent: Vec<Utxo>,
}

#[uniffi::export]
impl WalletHandle {
    /// Construct a wallet from `(seed, nonce, passphrase, kdf)`.
    ///
    /// `backend` is the network provider name (`"blockchain.info"` /
    /// `"blockstream"` / `"mempool.space"`; v0.3 also accepts
    /// `"auto"` — per-request failover across the three in registry
    /// order, first success wins, sticky for the handle's lifetime);
    /// `None` uses the process default.
    ///
    /// `nonce` is the starting BIP-44 derivation index. The handle
    /// derives addresses on demand starting from `nonce` — the scan
    /// methods always walk from `nonce` and stop at the gap limit
    /// (BIP-44). v1 fixes `nonce = 0`; non-zero values are accepted
    /// for completeness but the wallet's gap-limit walk still starts
    /// from this seed/nonce pair.
    ///
    /// `strict_bip39` selects the seed-reception policy (specs/spec.md
    /// «Seed policy», R-1…R-5): `false` (default everywhere) is
    /// permissive — any non-empty phrase is accepted; `true` is the
    /// opt-in strict BIP-39 mode — full BIP-39 parse plus the C6
    /// entropy floor, rejection is blocking BEFORE any KDF work
    /// (R-4). In both modes the empty phrase fails with
    /// [`YubtcError::EmptySeed`] (R-2).
    ///
    /// `addr_type` selects the receive-address form (specs/spec.md
    /// «Адресная политика и nonce→path mapping»): `native` (default)
    /// → P2WPKH, `taproot` → P2TR key-path, `legacy` → the v0.1
    /// P2PKH encoding. For `pbkdf2` wallets the type picks the
    /// BIP-32 leaf (`m/44'…`/`m/84'…`/`m/86'…`); for the other KDFs
    /// the same key is re-encoded (вариант A, ОВ-2). Scan results
    /// always include UTXOs of every form.
    #[uniffi::constructor]
    pub fn new(
        seed: String,
        nonce: u32,
        passphrase: String,
        kdf: KdfAlgoName,
        backend: Option<String>,
        strict_bip39: bool,
        addr_type: AddrTypeName,
    ) -> Result<Arc<Self>, YubtcError> {
        let resolved: std::sync::Arc<dyn net::NetworkBackend> = match backend.as_deref() {
            Some(name) if !name.is_empty() => net::get_backend(name)?,
            _ => net::get_backend("blockchain.info")?,
        };
        let seed_t = TSeed::new(seed);
        let pass_t = TPassphrase::new(passphrase);
        let kdf_t: KdfAlgo = kdf.into();
        let addr_type_t: wallet::AddrType = addr_type.into();
        // Seed-reception policy (C8): strict violations and the empty
        // phrase stop here — before any KDF work (R-2/R-4).
        validate_reception(&seed_t, strict_bip39)?;
        // Validate seed + passphrase + kdf + addr_type combination by
        // deriving the starting privkey up front. This catches the
        // empty seed and the wrong KDF / passphrase combos before the
        // first network call.
        let _ = TPrivKey::with_addr_type(&seed_t, TNonce::new(nonce), &pass_t, kdf_t, addr_type_t)?;
        Ok(Arc::new(Self {
            seed: seed_t,
            passphrase: pass_t,
            kdf: kdf_t,
            addr_type: addr_type_t,
            backend: std::sync::RwLock::new(resolved),
            cache: Mutex::new(None),
        }))
    }

    /// Mainnet P2PKH address for the wallet's primary nonce.
    ///
    /// Legacy shortcut (spec: the method is kept for v0.1 callers) —
    /// equivalent to deriving nonce=0 from the handle's
    /// seed/passphrase/kdf at [`AddrTypeName::Legacy`], regardless of
    /// the handle's own `addr_type`. Returned as a string so the
    /// foreign side can display it without touching the FFI
    /// internals.
    pub fn p2pkh_address(&self) -> String {
        // Failure here would mean the constructor's invariant
        // broke — the seed/passphrase/kdf that produced the handle
        // can no longer derive the primary key. Should be
        // impossible; if it happens we surface a loud error rather
        // than an empty string.
        match TPrivKey::new(&self.seed, TNonce::new(0), &self.passphrase, self.kdf) {
            Ok(pk) => pk.get_p2pkh_address().as_str().to_string(),
            Err(e) => format!("yubtc: invariant violated (nonce=0 derivation failed: {e})"),
        }
    }

    /// Receiving address for the wallet's primary nonce, encoded in
    /// the handle's [`AddrTypeName`] form (`bc1q…` for native,
    /// `bc1p…` for taproot, `1…` for legacy).
    pub fn receiving_address(&self) -> Result<String, YubtcError> {
        // Invariant: `new_with_backend` already derived with the same
        // seed/passphrase/kdf/addr-type tuple and rejected the empty
        // seed and the passphrase-required KDF mismatch up front, so
        // this derivation cannot fail post-construction.
        let pk = TPrivKey::with_addr_type(
            &self.seed,
            TNonce::new(0),
            &self.passphrase,
            self.kdf,
            self.addr_type,
        )
        .expect("derivation validated at handle construction");
        Ok(pk.get_address().as_str().to_string())
    }

    /// Mainnet compressed WIF for the wallet's primary nonce.
    pub fn privwif(&self) -> Result<String, YubtcError> {
        let pk = TPrivKey::new(&self.seed, TNonce::new(0), &self.passphrase, self.kdf)?;
        Ok(pk.get_privwif())
    }

    /// Address info (balance / tx count) for the primary address.
    pub fn address_info(&self) -> Result<AddressInfoRecord, YubtcError> {
        let pk = TPrivKey::new(&self.seed, TNonce::new(0), &self.passphrase, self.kdf)?;
        let backend = self.current_backend();
        let info = block_on(net::get_address_info(
            backend.as_ref(),
            &pk.get_p2pkh_address(),
        ))?;
        Ok(info.into())
    }

    /// Switch this handle's network backend by name. Pass `None`
    /// (or empty) for the default (`blockchain.info`). Evicts the
    /// cached scan — the on-chain view is provider-specific.
    ///
    /// Known names mirror [`yubtc_core::net::get_backend`]:
    /// `blockchain.info`, `blockstream`, `mempool.space`, and the
    /// v0.3 `auto` (failover across the three in registry order —
    /// see `net::AutoBackend`). There is no listing function over
    /// FFI; this doc is the registry surface.
    ///
    /// Backend injection architecture: the backend is handle-local
    /// (there is no process-global one), so switching affects only
    /// this handle.
    pub fn set_backend(&self, name: Option<String>) -> Result<(), YubtcError> {
        let resolved = match name.as_deref() {
            Some(s) if !s.is_empty() => net::get_backend(s)?,
            _ => net::get_backend("blockchain.info")?,
        };
        *self.backend.write().expect("backend lock poisoned") = resolved;
        self.lock();
        Ok(())
    }

    /// Eager scan: return every UTXO at every contributing address,
    /// in scan order.
    ///
    /// `confirmations` is the per-UTXO depth filter (default
    /// [`crate::fwd::DEFAULT_CONFIRMATIONS`] when 0).
    ///
    /// The first call performs a network round-trip per contributing
    /// address (`O(K · R)`); subsequent calls return the cached
    /// result. The cache is evicted by [`Self::lock`] and by
    /// `set_backend` (different provider → different view).
    pub fn all_unspent(&self, confirmations: u32) -> Result<Vec<UtxoWithNonce>, YubtcError> {
        let cache = scan_all_cached(self, confirmations)?;
        Ok(flatten_cache(&cache, confirmations))
    }

    /// Lazy scan: walk addresses until `target_sat` is met or the
    /// gap limit is reached.
    ///
    /// When `target_sat` is `None` the scan is eager (same as
    /// [`Self::all_unspent`]). When `Some(_)`, the scan stops as
    /// soon as the cumulative UTXO value reaches `target_sat` —
    /// that's the CLI/Python parity path (`send ADDR AMOUNT`).
    ///
    /// Returns the contributing `(nonce, txid, vout)` references,
    /// the matching `UtxoWithNonce` array, and the cashback address
    /// (gap-limit unused on gap stop; last sourced on target-met).
    pub fn select_inputs_until(
        &self,
        target_sat: Option<u64>,
        confirmations: u32,
    ) -> Result<SelectInputsResult, YubtcError> {
        let target = target_sat.map(TSatoshi::new);
        let cache = scan_until_cached(self, target, confirmations)?;
        let selected: Vec<SelectedSource> = cache
            .entries
            .iter()
            .flat_map(|e| {
                e.unspent.iter().map(move |u| SelectedSource {
                    nonce: e.nonce,
                    txid_hex: hex::encode(u.txid),
                    vout: u.vout,
                })
            })
            .collect();
        let utxos = flatten_cache(&cache, confirmations);
        Ok(SelectInputsResult {
            selected,
            utxos,
            cashback_addr: cache.cashback_addr.as_str().to_string(),
        })
    }

    /// Build and sign a transaction from a user-picked UTXO set.
    ///
    /// `utxos` is the full set the caller has on hand (typically
    /// the `utxos` field of [`SelectInputsResult`] or the result of
    /// [`Self::all_unspent`]). `selected` is the subset to spend.
    /// `cashback_addr` is required — the caller passes the
    /// cashback address returned by the scan (gap-limit unused or
    /// last sourced), or any address it owns. `bc1…` cashback and
    /// destination addresses are accepted (P2WPKH / P2TR outputs).
    ///
    /// **Validation.** Every `(nonce, txid, vout)` in `selected`
    /// must be present in `utxos` at the same nonce; otherwise the
    /// call is rejected with `YubtcError::Invalid`. This catches
    /// stale picker selections without silently dropping inputs.
    ///
    /// `amount_sat` is `None` for a full drain; `fee_sat == 0` runs
    /// the wallet's fee loop using `feekb_sat` as the target rate.
    /// The privkeys for each unique `(nonce, script_type)` in
    /// `selected` are re-derived from the handle's
    /// seed/passphrase/kdf (`pbkdf2` wallets have a distinct key per
    /// address form; вариант-A KDFs re-encode the same key), so the
    /// caller doesn't have to keep them. The signed transaction is
    /// serialised with the **wire** layout — a witness transaction
    /// broadcast as stripped bytes would be rejected by every node.
    #[allow(clippy::too_many_arguments)]
    pub fn make_transaction_multi(
        &self,
        utxos: Vec<UtxoWithNonce>,
        selected: Vec<SelectedSource>,
        cashback_addr: String,
        dst: String,
        amount_sat: Option<u64>,
        feekb_sat: u64,
        fee_sat: u64,
    ) -> Result<TxResultRecord, YubtcError> {
        // Validate cashback + dst addresses.
        let cashback = TAddress::new(cashback_addr);
        let dst_addr = TAddress::new(dst);
        // Validate the selection against `utxos`. We index utxos
        // by (nonce, txid, vout) for O(1) lookup; missing entries
        // abort the whole call with Invalid. Each entry also carries
        // the `script_type` needed to re-derive the spending key.
        let mut by_key: std::collections::HashMap<(u32, [u8; 32], u32), (Utxo, String)> =
            std::collections::HashMap::with_capacity(utxos.len());
        // Track which `(nonce, script_type)` groups contributed so we
        // can derive privkeys exactly once per group.
        let mut needed_groups: std::collections::BTreeSet<(u32, String)> =
            std::collections::BTreeSet::new();
        for u in utxos {
            let txid_bytes = hex::decode(&u.txid_hex)
                .map_err(|e| YubtcError::Invalid(format!("bad utxo txid hex: {e}")))?;
            if txid_bytes.len() != 32 {
                return Err(YubtcError::Invalid(format!(
                    "utxo txid must be 32 bytes (got {})",
                    txid_bytes.len()
                )));
            }
            let mut txid = [0u8; 32];
            txid.copy_from_slice(&txid_bytes);
            let key = (u.nonce, txid, u.vout);
            let entry = (
                Utxo {
                    txid,
                    vout: u.vout,
                    amount: u.amount_sat,
                    script_pubkey: Vec::new(), // filled in below from the group key
                    confirmations: u.confirmations,
                },
                u.script_type,
            );
            if by_key.insert(key, entry).is_some() {
                return Err(YubtcError::Invalid(format!(
                    "duplicate (nonce={}, txid={}, vout={}) in utxos",
                    key.0,
                    hex::encode(key.1),
                    key.2
                )));
            }
        }
        // Decode and validate the selection. Reject any selected
        // entry whose `(nonce, txid, vout)` isn't in `utxos`. The
        // validated keys are remembered so the grouping pass below
        // doesn't re-decode the same hex a second time.
        let mut selected_keys: Vec<(u32, [u8; 32], u32)> = Vec::with_capacity(selected.len());
        for s in &selected {
            let txid_bytes = hex::decode(&s.txid_hex)
                .map_err(|e| YubtcError::Invalid(format!("bad selected txid hex: {e}")))?;
            if txid_bytes.len() != 32 {
                return Err(YubtcError::Invalid(format!(
                    "selected txid must be 32 bytes (got {})",
                    txid_bytes.len()
                )));
            }
            let mut txid = [0u8; 32];
            txid.copy_from_slice(&txid_bytes);
            let key = (s.nonce, txid, s.vout);
            if !by_key.contains_key(&key) {
                return Err(YubtcError::Invalid(format!(
                    "selected UTXO (nonce={}, txid={}, vout={}) not in utxos",
                    s.nonce, s.txid_hex, s.vout
                )));
            }
            selected_keys.push(key);
            let (_, script_type) = by_key
                .get(&key)
                .expect("selected UTXO presence in by_key was validated above");
            needed_groups.insert((s.nonce, script_type.clone()));
        }
        // Group selected UTXOs by `(nonce, script_type)` — one Source
        // per group. Each group carries the privkey derived for that
        // address form and the subset of selected UTXOs in it. Every
        // key here was validated against `by_key` in the loop above,
        // so the lookup cannot miss.
        let mut grouped: std::collections::BTreeMap<(u32, String), Vec<Utxo>> =
            std::collections::BTreeMap::new();
        for key in &selected_keys {
            let (entry, script_type) = by_key
                .get(key)
                .expect("selected UTXO presence in by_key was validated above")
                .clone();
            grouped.entry((key.0, script_type)).or_default().push(entry);
        }
        // Derive the privkey of each `(nonce, form)` group, fill in
        // `script_pubkey` from the group key so `build_vin` can
        // verify the lock script, and assemble Sources.
        let mut sources: Vec<Source> = Vec::with_capacity(needed_groups.len());
        for group in &needed_groups {
            let (nonce, script_type) = group;
            let addr_type = addr_type_of_script_type(script_type)?;
            // Invariant: the handle's seed is non-empty and its
            // passphrase/kdf pair was validated at construction, and
            // derivation itself is total for any nonce/addr type, so
            // this cannot fail post-construction.
            let pk = TPrivKey::with_addr_type(
                &self.seed,
                TNonce::new(*nonce),
                &self.passphrase,
                self.kdf,
                addr_type,
            )
            .expect("derivation validated at handle construction");
            // `grouped` was populated from the same `selected` set
            // that filled `needed_groups`, so the remove always hits.
            let mut utxos_for_pk = grouped
                .remove(group)
                .expect("group in grouped was populated from the same selected set");
            // Fill in script_pubkey for each UTXO so build_vin can
            // verify the lock script against the group key's pubkey.
            // Entries arrive with an empty script (only this function
            // constructs them, and only here is it filled), so the
            // assignment is unconditional.
            let script = own_lock_script(&pk, addr_type);
            for u in &mut utxos_for_pk {
                u.script_pubkey = script.clone();
            }
            sources.push(Source {
                privkey: pk,
                unspent: utxos_for_pk,
            });
        }
        let amount = amount_sat.map(TSatoshi::new);
        let wallet = Wallet::from_privkeys(
            TSeed::new(""), // unused by make_transaction when sources are provided
            TPassphrase::EMPTY,
            self.kdf,
            self.addr_type,
            self.current_backend(),
            sources.iter().map(|s| s.privkey.clone()).collect(),
        );
        let result = block_on(wallet.make_transaction(
            &dst_addr,
            amount,
            TSatoshi::new(feekb_sat),
            TSatoshi::new(fee_sat),
            0,
            Some(sources),
            Some(cashback),
        ))?;
        Ok(TxResultRecord {
            // Wire layout (BIP-144): a witness transaction broadcast
            // in the stripped layout would be rejected by every node;
            // witness-free transactions serialise byte-identically to
            // v0.1.
            tx_hex: hex::encode(result.tx.serialize_wire()),
            txid_hex: hex::encode(result.tx.id()),
            cashback_sat: result.cashback.get(),
            amount_sat: result.amount.get(),
            fee_sat: result.fee.get(),
        })
    }

    /// Broadcast a signed transaction. `raw_tx_hex` is the wire-format
    /// payload (the same bytes `make_transaction_multi().tx_hex`
    /// returns). Returns the node's txid on success.
    pub fn broadcast(&self, raw_tx_hex: String) -> Result<String, YubtcError> {
        let bytes = hex::decode(raw_tx_hex).map_err(|e| YubtcError::Invalid(e.to_string()))?;
        let backend = self.current_backend();
        block_on(net::broadcast(backend.as_ref(), &bytes))?;
        // Re-derive the txid so the caller doesn't have to re-serialize.
        // Txid = double-SHA256 of the wire bytes, reversed.
        let txid = double_sha256_reversed(&bytes);
        Ok(hex::encode(txid))
    }

    /// Signer role over a PSBT (BIP-174, spec ОВ-7 — FFI-only in
    /// v0.2; the UI arrives with multi-sig in Phase 15).
    ///
    /// `psbt_b64` is the PSBT in its base64 transport encoding. The
    /// handle's `(seed, passphrase, kdf)` drives the bounded offline
    /// nonce walk (`0..PSBT_SIGN_MAX_NONCE` × 3 address forms, ОВ-9):
    /// own inputs gain a `PARTIAL_SIG`, foreign inputs / inputs
    /// without UTXO data stay untouched (BIP-174 MUST). No network is
    /// touched — everything the Signer needs is in the PSBT. Returns
    /// the signed PSBT in the same base64 encoding (canonical wire
    /// form; unknown pairs carried byte-for-byte).
    pub fn psbt_sign(&self, psbt_b64: String) -> Result<String, YubtcError> {
        let mut psbt = crate::psbt::PartiallySignedTransaction::from_base64(&psbt_b64)?;
        wallet::sign_psbt_with(&self.seed, &self.passphrase, self.kdf, &mut psbt)?;
        Ok(psbt.to_base64())
    }

    /// Extractor role (BIP-174, spec ОВ-7): every input must be
    /// finalized, otherwise the call fails without modifying anything.
    /// Returns the completed transaction in wire format (BIP-144),
    /// hex-encoded — the exact payload [`WalletHandle::broadcast`]
    /// accepts.
    pub fn psbt_extract(&self, psbt_b64: String) -> Result<String, YubtcError> {
        let psbt = crate::psbt::PartiallySignedTransaction::from_base64(&psbt_b64)?;
        let tx = psbt.extract_transaction()?;
        Ok(hex::encode(tx.serialize_wire()))
    }

    /// Human-readable PSBT digest (`psbt decode`; not a BIP-174
    /// role). Pure function over the PSBT: no network, no signing.
    /// `fee_sat` is `None` when some input lacks UTXO data (warning
    /// situation per spec — the decoder must work on PSBT data alone).
    pub fn psbt_decode(&self, psbt_b64: String) -> Result<PsbtSummaryRecord, YubtcError> {
        let psbt = crate::psbt::PartiallySignedTransaction::from_base64(&psbt_b64)?;
        Ok(psbt.summary().into())
    }

    /// Multi-sig quorum address (Phase 15, R-MS-1 at the FFI level):
    /// validate the `(n, m, keys)` tuple and derive the fixed quorum
    /// address + canonical redeem script in the `form` encoding.
    ///
    /// `n` and `m` are **required** parameters — no `Option`, no
    /// default (R-MS-1). `form` is required too (v0.3 — no default at
    /// the FFI boundary): `P2sh` addresses the quorum as `3…`
    /// (base58check), `P2wsh` as `bc1q…` (bech32 v0, SHA-256
    /// commitment), `P2tr` as `bc1p…` (bech32m v1, script-path). The
    /// `keys` encoding follows the form (R-MS-10): compressed pubkeys
    /// as 66-char hex (`02…`/`03…`) for p2sh/p2wsh, x-only keys as
    /// 64-char hex for p2tr. WIFs do not cross the FFI boundary
    /// (R-MS-6 — secrets stay inside the handle). When `nonce` is
    /// `Some`, the own legacy-form key is derived from the handle's
    /// seed at that nonce and appended to the quorum; `None` is a
    /// watch-only create (the quorum consists of the passed keys
    /// alone). Offline: no network is touched. For `P2tr` the record
    /// additionally carries the taproot witness material
    /// (`internal_key_hex`/`control_block_hex`).
    pub fn ms_create_address(
        &self,
        n: u32,
        m: u32,
        keys: Vec<String>,
        nonce: Option<u32>,
        form: MsFormName,
    ) -> Result<MsAddressRecord, YubtcError> {
        let form: wallet::MsForm = form.into();
        let mut quorum = wallet::parse_ms_keys(&keys, form)?;
        if let Some(nonce) = nonce {
            // Invariant: the handle's seed/passphrase/kdf were
            // validated by the constructor's own derivation, and the
            // own-key derivation is total for any nonce, so this
            // cannot fail post-construction.
            quorum.push(
                wallet::ms_own_pubkey(&self.seed, TNonce::new(nonce), &self.passphrase, self.kdf)
                    .expect("derivation validated at handle construction"),
            );
        }
        let (addr, redeem) = wallet::ms_create_address(n as usize, m as usize, &quorum, form)?;
        let (internal_key_hex, control_block_hex) = match form {
            wallet::MsForm::P2tr => {
                let leaf_hash = crate::script::tapscript_leaf_hash(&redeem);
                let control = crate::address::tapscript_control_block(
                    &crate::fwd::MS_TAPSCRIPT_INTERNAL_KEY,
                    &leaf_hash,
                )
                .expect("NUMS lift and tweak are total for the canonical internal key");
                (
                    Some(hex::encode(crate::fwd::MS_TAPSCRIPT_INTERNAL_KEY)),
                    Some(hex::encode(control)),
                )
            }
            wallet::MsForm::P2sh | wallet::MsForm::P2wsh => (None, None),
        };
        Ok(MsAddressRecord {
            address: addr.as_str().to_string(),
            redeem_script_hex: hex::encode(redeem),
            internal_key_hex,
            control_block_hex,
        })
    }

    /// UTXOs of the multi-sig quorum address (ОВ-13): a direct
    /// `get_unspent` — the Phase 13 nonce walk (`all_unspent`) never
    /// sees the quorum address, so this is the only UTXO source for
    /// `MsSendScreen`. `confirmations` filters by depth (`0` = no
    /// filter, same convention as `all_unspent`).
    ///
    /// The returned [`UtxoWithNonce`] reuses the Coin Control record
    /// shape; the `nonce` field is the `0` sentinel for every row —
    /// a quorum address has no derivation nonce. Pass the full set
    /// back to [`Self::ms_build_psbt`] together with the picked
    /// [`SelectedSource`] subset.
    pub fn ms_unspent(
        &self,
        address: String,
        confirmations: u32,
    ) -> Result<Vec<UtxoWithNonce>, YubtcError> {
        let addr = TAddress::new(address);
        let backend = self.current_backend();
        let unspent = block_on(async { backend.get_unspent(&addr).await })?;
        let mut out = Vec::new();
        for u in unspent {
            if confirmations > 0 && u.confirmations < confirmations {
                continue;
            }
            out.push(UtxoWithNonce {
                // Quorum UTXOs carry the 0 sentinel: identity is
                // (txid, vout) at the single fixed address (ОВ-13).
                nonce: 0,
                txid_hex: hex::encode(u.txid),
                vout: u.vout,
                amount_sat: u.amount,
                confirmations: u.confirmations,
                script_type: script_type_name(&u.script_pubkey).to_string(),
            });
        }
        Ok(out)
    }

    /// Build + self-sign the quorum-spend PSBT (Creator + Signer in
    /// one step, ОВ-12) over a user-picked UTXO subset — the
    /// `make_transaction_multi` form (решение #12 Coin Control) of
    /// the library Creator [`wallet::ms_create_psbt`].
    ///
    /// `utxos` is the full set the caller has on hand (typically
    /// [`Self::ms_unspent`] output); `selected` is the subset to
    /// spend — every entry must be present in `utxos` (validated
    /// like [`Self::make_transaction_multi`], stale picker
    /// selections are rejected with `YubtcError::Invalid`). `fee_sat
    /// == 0` runs the wallet's fee loop at the `feekb_sat` rate.
    /// `n`/`m` are required (R-MS-1); the `keys` encoding follows
    /// the `form` (R-MS-10 — compressed 66-char hex for
    /// p2sh/p2wsh, x-only 64-char hex for p2tr); `nonce = Some(_)`
    /// derives the own key — `None` is refused with
    /// `MsError::NotAParticipant` (yubtc builds spends only of
    /// quorums it participates in). The result already
    /// carries the own partial signatures; cosigners sign
    /// out-of-band via [`Self::psbt_sign`], and the finalized PSBT
    /// goes through [`Self::psbt_extract`] + [`Self::broadcast`].
    #[allow(clippy::too_many_arguments)]
    pub fn ms_build_psbt(
        &self,
        dst: String,
        amount_sat: u64,
        n: u32,
        m: u32,
        keys: Vec<String>,
        nonce: Option<u32>,
        utxos: Vec<UtxoWithNonce>,
        selected: Vec<SelectedSource>,
        feekb_sat: u64,
        fee_sat: u64,
        form: MsFormName,
    ) -> Result<MsPsbtRecord, YubtcError> {
        let nonce = nonce.ok_or(crate::wallet::MsError::NotAParticipant)?;
        let own_privkey =
            wallet::ms_own_privkey(&self.seed, TNonce::new(nonce), &self.passphrase, self.kdf)?;
        let form: wallet::MsForm = form.into();
        let mut quorum = wallet::parse_ms_keys(&keys, form)?;
        quorum.push(crate::privkey::privkey_to_pubkey(&own_privkey));
        let (_, redeem) = wallet::ms_create_address(n as usize, m as usize, &quorum, form)?;
        let quorum_script = wallet::ms_quorum_lock_script(&redeem, form);

        // Validate the selection against the full UTXO view, then
        // take the picked rows in the caller's order (deduplicated —
        // a doubled pick would double-spend one prevout).
        let dst_addr = TAddress::new(dst);
        let mut by_key: std::collections::HashMap<(u32, [u8; 32], u32), Utxo> =
            std::collections::HashMap::with_capacity(utxos.len());
        for u in utxos {
            let txid_bytes = match hex::decode(&u.txid_hex) {
                Ok(v) => v,
                Err(e) => {
                    return Err(YubtcError::Invalid(format!("bad utxo txid hex: {e}")));
                }
            };
            let txid: [u8; 32] = match txid_bytes.try_into() {
                Ok(v) => v,
                Err(v) => {
                    return Err(YubtcError::Invalid(format!(
                        "utxo txid must be 32 bytes (got {})",
                        v.len()
                    )));
                }
            };
            let key = (u.nonce, txid, u.vout);
            let entry = Utxo {
                txid,
                vout: u.vout,
                amount: u.amount_sat,
                // Filled from the quorum script below — the caller's
                // per-row script shape is not trusted for spends.
                script_pubkey: Vec::new(),
                confirmations: u.confirmations,
            };
            if by_key.insert(key, entry).is_some() {
                return Err(YubtcError::Invalid(format!(
                    "duplicate (nonce={}, txid={}, vout={}) in utxos",
                    key.0,
                    hex::encode(key.1),
                    key.2
                )));
            }
        }
        let mut picked: Vec<Utxo> = Vec::with_capacity(selected.len());
        let mut seen: std::collections::BTreeSet<(u32, [u8; 32], u32)> =
            std::collections::BTreeSet::new();
        for s in selected {
            let txid_bytes = match hex::decode(&s.txid_hex) {
                Ok(v) => v,
                Err(e) => {
                    return Err(YubtcError::Invalid(format!("bad selected txid hex: {e}")));
                }
            };
            let txid: [u8; 32] = match txid_bytes.try_into() {
                Ok(v) => v,
                Err(v) => {
                    return Err(YubtcError::Invalid(format!(
                        "selected txid must be 32 bytes (got {})",
                        v.len()
                    )));
                }
            };
            let key = (s.nonce, txid, s.vout);
            if !by_key.contains_key(&key) {
                return Err(YubtcError::Invalid(format!(
                    "selected UTXO (nonce={}, txid={}, vout={}) not in utxos",
                    s.nonce, s.txid_hex, s.vout
                )));
            }
            if !seen.insert(key) {
                return Err(YubtcError::Invalid(format!(
                    "duplicate selected UTXO (nonce={}, txid={}, vout={})",
                    s.nonce, s.txid_hex, s.vout
                )));
            }
            let mut entry = by_key
                .get(&key)
                .expect("selected UTXO presence in by_key was validated above")
                .clone();
            entry.script_pubkey = quorum_script.clone();
            picked.push(entry);
        }

        let outcome = block_on(wallet::ms_build_psbt_from_selected(
            &own_privkey,
            &dst_addr,
            TSatoshi::new(amount_sat),
            m as usize,
            &redeem,
            &picked,
            self.current_backend().as_ref(),
            TSatoshi::new(feekb_sat),
            TSatoshi::new(fee_sat),
            form,
        ))?;
        Ok(MsPsbtRecord {
            psbt_b64: outcome.psbt_b64,
            fee_sat: outcome.fee.get(),
        })
    }

    /// Drop the cached scan output. Subsequent calls to
    /// `all_unspent` / `select_inputs_until` re-fetch from the
    /// backend. Use after a broadcast (`txid` confirmation may
    /// unblock new UTXOs) or when switching wallets.
    pub fn lock(&self) {
        // The JNA-side handle is the only owner of the secret
        // material on the foreign side; clearing the cache here
        // guarantees the next operation re-derives everything
        // from scratch.
        let mut cache = self.cache.lock().expect("yubtc cache poisoned");
        *cache = None;
    }
}

/// Non-FFI helpers: `#[uniffi::export] impl` blocks pick up every
/// method inside them, so backend plumbing with non-FFI types lives
/// here instead.
impl WalletHandle {
    /// Clone of the handle's backend (read-locked briefly).
    fn current_backend(&self) -> Arc<dyn net::NetworkBackend> {
        self.backend.read().expect("backend lock poisoned").clone()
    }

    /// Test-only constructor with an injected backend instance
    /// (wiremock URLs, in-memory mocks) — the FFI constructor only
    /// takes provider names. Validates exactly like
    /// [`WalletHandle::new`]: the reception policy runs first, then
    /// the nonce-0 key derivation at the requested `addr_type`.
    /// `strict_bip39` / `addr_type` carry the same meanings as in
    /// [`WalletHandle::new`].
    #[cfg(test)]
    pub(crate) fn new_with_backend(
        seed: String,
        nonce: u32,
        passphrase: String,
        kdf: KdfAlgoName,
        backend: Arc<dyn net::NetworkBackend>,
        strict_bip39: bool,
        addr_type: AddrTypeName,
    ) -> Result<Arc<Self>, YubtcError> {
        let seed_t = TSeed::new(seed);
        let pass_t = TPassphrase::new(passphrase);
        let kdf_t: KdfAlgo = kdf.into();
        let addr_type_t: wallet::AddrType = addr_type.into();
        validate_reception(&seed_t, strict_bip39)?;
        let pk = wallet::TPrivKey::with_addr_type(
            &seed_t,
            TNonce::new(nonce),
            &pass_t,
            kdf_t,
            addr_type_t,
        )?;
        let _ = pk.get_address();
        Ok(Arc::new(Self {
            seed: seed_t,
            passphrase: pass_t,
            kdf: kdf_t,
            addr_type: addr_type_t,
            backend: std::sync::RwLock::new(backend),
            cache: Mutex::new(None),
        }))
    }
}

/// Flatten a scan cache to `Vec<UtxoWithNonce>`, optionally
/// filtering by minimum confirmations.
///
/// `confirmations == 0` means "no filter" (return everything in the
/// cache). The cache stores the raw per-UTXO confirmations reported
/// by the backend; the filter is applied here so changing the
/// threshold doesn't invalidate the cached scan. Each UTXO's
/// `script_type` is classified from its `scriptPubKey` shape.
fn flatten_cache(cache: &ScanCache, confirmations: u32) -> Vec<UtxoWithNonce> {
    let mut out: Vec<UtxoWithNonce> = Vec::new();
    for e in &cache.entries {
        for u in &e.unspent {
            if confirmations > 0 && u.confirmations < confirmations {
                continue;
            }
            out.push(UtxoWithNonce {
                nonce: e.nonce,
                txid_hex: hex::encode(u.txid),
                vout: u.vout,
                amount_sat: u.amount,
                confirmations: u.confirmations,
                script_type: script_type_name(&u.script_pubkey).to_string(),
            });
        }
    }
    out
}

/// Eager scan, with cache lookup. Returns the cache so the
/// caller can reuse `cashback_addr` / per-entry privkeys.
fn scan_all_cached(handle: &WalletHandle, confirmations: u32) -> Result<ScanCache, YubtcError> {
    let mut guard = handle.cache.lock().expect("yubtc cache poisoned");
    if let Some(c) = guard.as_ref() {
        return Ok(c.clone());
    }
    let (sources, cashback) = block_on(wallet::scan_all(
        &handle.seed,
        &handle.passphrase,
        handle.kdf,
        handle.addr_type,
        handle.current_backend().as_ref(),
        confirmations,
    ))?;
    let entries: Vec<CacheEntry> = sources
        .into_iter()
        .map(|s| CacheEntry {
            nonce: s.privkey.nonce.get(),
            addr_type: s.privkey.addr_type,
            address: s.privkey.get_address(),
            privkey: s.privkey,
            unspent: s.unspent,
        })
        .collect();
    let cache = ScanCache {
        entries,
        cashback_addr: cashback,
    };
    *guard = Some(cache.clone());
    Ok(cache)
}

/// Lazy scan with target, with cache lookup.
fn scan_until_cached(
    handle: &WalletHandle,
    target: Option<TSatoshi>,
    confirmations: u32,
) -> Result<ScanCache, YubtcError> {
    // Target-scoped scans are NOT cacheable: each call has a
    // different target. Always re-scan.
    let (sources, cashback) = block_on(wallet::scan_inputs_until(
        &handle.seed,
        &handle.passphrase,
        handle.kdf,
        handle.addr_type,
        handle.current_backend().as_ref(),
        target,
        confirmations,
    ))?;
    let entries: Vec<CacheEntry> = sources
        .into_iter()
        .map(|s| CacheEntry {
            nonce: s.privkey.nonce.get(),
            addr_type: s.privkey.addr_type,
            address: s.privkey.get_address(),
            privkey: s.privkey,
            unspent: s.unspent,
        })
        .collect();
    let cache = ScanCache {
        entries,
        cashback_addr: cashback,
    };
    // Update the eager cache with whatever the lazy scan found.
    // The lazy scan's cashback may differ from the eager one
    // (last sourced vs gap-limit), so we record what THIS scan
    // saw rather than overwriting.
    let mut guard = handle.cache.lock().expect("yubtc cache poisoned");
    *guard = Some(cache.clone());
    Ok(cache)
}

/// Double-SHA256, then reverse the byte order (Bitcoin's display
/// order).
fn double_sha256_reversed(bytes: &[u8]) -> [u8; 32] {
    use sha2::Digest as _;
    let h1 = sha2::Sha256::digest(bytes);
    let h2 = sha2::Sha256::digest(h1);
    let mut out = [0u8; 32];
    let v = h2.as_slice();
    for i in 0..32 {
        out[i] = v[31 - i];
    }
    out
}

