/// Per-input line of [`PsbtSummaryRecord`] (the
/// `WalletHandle::psbt_decode` digest, spec ОВ-7).
#[derive(Debug, Clone, uniffi::Record)]
pub struct PsbtInputSummaryRecord {
    /// UTXO data (either field) is present.
    pub has_utxo: bool,
    /// Number of `PARTIAL_SIG` entries.
    pub n_partial_sigs: u64,
    /// Raw `SIGHASH_TYPE` field, if any.
    pub sighash_type: Option<u32>,
    /// A final field (`FINAL_SCRIPTSIG` or `FINAL_SCRIPTWITNESS`) is
    /// present.
    pub finalized: bool,
}

/// Per-output line of [`PsbtSummaryRecord`].
#[derive(Debug, Clone, uniffi::Record)]
pub struct PsbtOutputSummaryRecord {
    pub amount_sat: u64,
    pub script_pubkey_hex: String,
}

/// Human-readable PSBT digest (`WalletHandle::psbt_decode`; a yubtc
/// extension, not a BIP-174 role). `fee_sat` is `Some` only when every
/// input carries UTXO data (`Σ inputs − Σ outputs`); a missing UTXO is
/// a warning situation per spec, not an error.
#[derive(Debug, Clone, uniffi::Record)]
pub struct PsbtSummaryRecord {
    pub txid_hex: String,
    pub version: u32,
    pub inputs: Vec<PsbtInputSummaryRecord>,
    pub outputs: Vec<PsbtOutputSummaryRecord>,
    pub fee_sat: Option<u64>,
}

impl From<crate::psbt::PsbtSummary> for PsbtSummaryRecord {
    fn from(s: crate::psbt::PsbtSummary) -> Self {
        Self {
            txid_hex: s.txid_hex,
            version: s.version,
            inputs: s
                .inputs
                .into_iter()
                .map(|i| PsbtInputSummaryRecord {
                    has_utxo: i.has_utxo,
                    // usize → u64 is lossless on every supported
                    // platform (a partial-sig count, not a heap size).
                    n_partial_sigs: i.n_partial_sigs as u64,
                    sighash_type: i.sighash_type,
                    finalized: i.finalized,
                })
                .collect(),
            outputs: s
                .outputs
                .into_iter()
                .map(|o| PsbtOutputSummaryRecord {
                    amount_sat: o.amount_sat,
                    script_pubkey_hex: o.script_pubkey_hex,
                })
                .collect(),
            fee_sat: s.fee_sat,
        }
    }
}

/// Result of [`WalletHandle::ms_create_address`] (Phase 15, spec
/// «Принято (2026-09-02): полный surface»; v0.3 adds the P2WSH and
/// P2TR script-path forms): the fixed quorum address plus the
/// canonical redeem script (hex) it was built from. The address is
/// fixed by the `(N, M, keys)` tuple (ОВ-13) and encoded per the
/// selected form.
#[derive(Debug, Clone, uniffi::Record)]
pub struct MsAddressRecord {
    /// The quorum address: `3…` (P2SH), `bc1q…` (P2WSH) or `bc1p…`
    /// (P2TR script-path, bech32m v1).
    pub address: String,
    /// Canonical redeem script, BIP-67-sorted, hex-encoded: the bare
    /// `OP_m ‖ keys ‖ OP_n ‖ OP_CHECKMULTISIG` script for
    /// p2sh/p2wsh (R-MS-3/R-MS-4), the CHECKSIGADD tapscript for
    /// p2tr (R-MS-7 — different bytes for the same key set; the
    /// field name is unchanged for binding stability, spec
    /// «Multi-sig» / FFI).
    pub redeem_script_hex: String,
    /// p2tr only: the NUMS internal key of the single-leaf tree
    /// (32 bytes, hex — R-MS-8). `None` for p2sh/p2wsh.
    pub internal_key_hex: Option<String>,
    /// p2tr only: the 33-byte BIP-341 control block of the leaf
    /// (`c[0] ‖ internal key`, `33 = 33 + 32·depth` at depth 0,
    /// hex — 66 chars). `None` for p2sh/p2wsh.
    pub control_block_hex: Option<String>,
}

/// Result of [`WalletHandle::ms_build_psbt`]: the quorum-spend PSBT
/// (own partial signatures already included) plus the fee the fee
/// loop settled on (or the explicit fee).
#[derive(Debug, Clone, uniffi::Record)]
pub struct MsPsbtRecord {
    /// The PSBT in its base64 transport form (BIP-174). Cosigners
    /// sign it out-of-band (`psbt_sign`), then
    /// `psbt_decode`/`psbt_extract`/`broadcast` finish the chain.
    pub psbt_b64: String,
    /// The fee (sat) this build committed to.
    pub fee_sat: u64,
}

