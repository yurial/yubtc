/// Plain view of a UTXO with its derivation nonce.
///
/// `nonce` identifies the address that owns this output (BIP-44
/// `m/44'/0'/0'/0/<nonce>`). A UTXO is identified by the triple
/// `(nonce, txid, vout)` — not `(address, txid, vout)` — so the
/// address can be re-derived deterministically from the seed and
/// the foreign side doesn't have to round-trip it.
///
/// `script_type` names the output's address form (`p2pkh` / `p2sh` /
/// `p2wpkh` / `p2tr`): the scan reports UTXOs of every form the
/// wallet can own, and Coin Control labels each row accordingly. The
/// value is what [`WalletHandle::make_transaction_multi`] uses to
/// re-derive the spending key (`pbkdf2` wallets have a distinct key
/// per form).
#[derive(Debug, Clone, uniffi::Record)]
pub struct UtxoWithNonce {
    pub nonce: u32,
    pub txid_hex: String,
    pub vout: u32,
    pub amount_sat: u64,
    pub confirmations: u32,
    pub script_type: String,
}

/// Classify a `scriptPubKey` into the FFI `script_type` spelling.
/// Total: anything that is not a canonical P2WPKH / P2TR / P2PKH /
/// P2SH shape is `unknown` (the scan never produces it — UTXOs pass
/// `validate_utxo_script` first — but the helper is total so no
/// foreign caller can crash on a crafted cache).
fn script_type_name(script: &[u8]) -> &'static str {
    if crate::script::extract_p2wpkh_hash(script).is_ok() {
        "p2wpkh"
    } else if crate::script::extract_p2tr_output_key(script).is_ok() {
        "p2tr"
    } else if crate::script::extract_p2pkh_hash(script).is_ok() {
        "p2pkh"
    } else if script.len() == 23 && script[0] == 0xa9 && script[1] == 0x14 && script[22] == 0x87 {
        "p2sh"
    } else {
        "unknown"
    }
}

/// FFI `script_type` → core [`wallet::AddrType`]. `p2sh` and anything
/// unknown are rejected: the wallet never creates P2SH for itself, so
/// the scan can never report such a `script_type` and there is no key
/// to re-derive for it.
fn addr_type_of_script_type(script_type: &str) -> Result<wallet::AddrType, YubtcError> {
    match script_type {
        "p2pkh" => Ok(wallet::AddrType::Legacy),
        "p2wpkh" => Ok(wallet::AddrType::Native),
        "p2tr" => Ok(wallet::AddrType::Taproot),
        other => Err(YubtcError::Unsupported(format!(
            "unsupported script_type: {other} (the wallet cannot spend it)"
        ))),
    }
}

/// Lock script of the address `pk` was derived for (the form the
/// scan reported for the UTXOs this key spends).
fn own_lock_script(pk: &TPrivKey, addr_type: wallet::AddrType) -> Vec<u8> {
    let pubkey = crate::privkey::privkey_to_pubkey(&pk.privkey);
    match addr_type {
        wallet::AddrType::Legacy => {
            crate::script::make_p2pkh_lock_script(&crate::address::hash160_pubkey(&pubkey))
        }
        wallet::AddrType::Native => {
            crate::script::make_p2wpkh_lock_script(&crate::address::hash160_pubkey(&pubkey))
                .to_vec()
        }
        wallet::AddrType::Taproot => {
            let mut xonly = [0u8; 32];
            xonly.copy_from_slice(&pubkey[1..33]);
            let output_key = crate::address::taproot_output_key(&xonly).expect(
                "TapTweak infinity (p ≈ 2^-128) for a valid curve point: documented invariant",
            );
            crate::script::make_p2tr_lock_script(&output_key).to_vec()
        }
    }
}

/// Foreign-side reference to a UTXO across all wallet addresses.
///
/// Used by Coin Control (Android) and `select_inputs_until`
/// (CLI/Python parity). Identified by `(nonce, txid_hex, vout)` —
/// `nonce` is the BIP-44 derivation index of the owning address,
/// `txid_hex` is the 32-byte display-order double-SHA256 hex (same
/// shape as `UtxoWithNonce::txid_hex`).
#[derive(Debug, Clone, PartialEq, Eq, Hash, uniffi::Record)]
pub struct SelectedSource {
    pub nonce: u32,
    pub txid_hex: String,
    pub vout: u32,
}

/// Result of [`WalletHandle::select_inputs_until`].
///
/// `selected` are the UTXOs the scan consumed (every UTXO on every
/// contributing address, regardless of whether the cumulative sum
/// reached `target_sat`). `utxos` is the same set in
/// [`UtxoWithNonce`] form — the caller passes it back to
/// [`WalletHandle::make_transaction_multi`] without re-fetching.
///
/// `cashback_addr` is the gap-limit unused address (scan stopped at
/// the BIP-44 gap) or the last sourced address (scan stopped when
/// `target_sat` was met). The caller is responsible for using it
/// verbatim.
#[derive(Debug, Clone, uniffi::Record)]
pub struct SelectInputsResult {
    pub selected: Vec<SelectedSource>,
    pub utxos: Vec<UtxoWithNonce>,
    pub cashback_addr: String,
}

