/// Greedy default input selection.
///
/// Pure function over the caller-supplied `utxos` (typically the
/// `Vec<UtxoWithNonce>` returned by
/// [`WalletHandle::all_unspent`]). No network access.
///
/// **Algorithm.** Sort `(nonce, vout)` ascending, take UTXOs until
/// `target_sat` is met (or all UTXOs if `target_sat` is `None` or
/// unreachable). The output is the smallest prefix of that order
/// that covers the target — matches Python's
/// `select.default_selection`.
///
/// Used by the Android "Auto-pick" button on the UTXO picker:
/// the user doesn't want to pick manually, so the picker
/// substitutes a deterministic default.
#[uniffi::export]
pub fn default_selection(
    utxos: Vec<UtxoWithNonce>,
    target_sat: Option<u64>,
) -> Vec<SelectedSource> {
    let mut sorted = utxos;
    sorted.sort_by_key(|u| (u.nonce, u.vout));
    let mut total: u64 = 0;
    let mut out: Vec<SelectedSource> = Vec::new();
    for u in &sorted {
        if let Some(t) = target_sat {
            if total >= t {
                break;
            }
        }
        out.push(SelectedSource {
            nonce: u.nonce,
            txid_hex: u.txid_hex.clone(),
            vout: u.vout,
        });
        total += u.amount_sat;
    }
    out
}

