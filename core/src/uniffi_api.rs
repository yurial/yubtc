/// Generate a fresh BIP-39 mnemonic with `word_count` words (12, 15,
/// 18, 21, or 24).
#[uniffi::export]
pub fn generate_seed(word_count: u8) -> Result<String, YubtcError> {
    let wc = match word_count {
        12 => 12usize,
        15 => 15usize,
        18 => 18usize,
        21 => 21usize,
        24 => 24usize,
        n => {
            return Err(YubtcError::Invalid(format!(
                "unsupported word count: {n} (allowed: 12, 15, 18, 21, 24)"
            )))
        }
    };
    // `generate_seed` cannot fail here: `wc` is one of the supported
    // word counts (validated above) and `DEFAULT_ALLOW_DUPS` skips the
    // duplicate-words guard, so the only error paths are unreachable.
    let s = crate::seed::generate_seed(wc, crate::fwd::DEFAULT_ALLOW_DUPS)
        .expect("invariant: word count validated above; duplicates allowed");
    Ok(s.as_str().to_string())
}

/// Validate a seed phrase under the selected reception policy
/// (specs/spec.md «Seed policy», R-1…R-5). Returns the same words, joined
/// by a single space, so the caller can normalise formatting.
///
/// Contract: `strict = false` (permissive, the system default)
/// accepts any non-empty phrase — no BIP-39 parse, no entropy floor;
/// `strict = true` requires a full BIP-39 parse (wordlist +
/// checksum, 12/15/18/21/24 words) plus the C6 entropy floor and
/// returns the rule violation in the error otherwise. The empty
/// phrase is rejected in both modes with the «empty seed phrase»
/// message. Never panics; performs no I/O.
#[uniffi::export]
pub fn validate_seed(seed: String, strict: bool) -> Result<String, YubtcError> {
    let s = TSeed::new(seed);
    crate::seed::validate_seed_with_policy(&s, seed_policy(strict))
        .map_err(|e| YubtcError::Invalid(e.to_string()))?;
    Ok(s.as_str().split_whitespace().collect::<Vec<_>>().join(" "))
}

/// Rough entropy estimate of an arbitrary phrase in bits
/// (`length * log2(|charset|)`, specs/spec.md «Seed policy», R-6). Shared
/// formula for the CLI warning and the UI warning — the estimate is
/// never computed outside the core.
///
/// Contract: any UTF-8 phrase; returns a finite non-negative value
/// (`0.0` for the empty phrase). Non-blocking by definition — see
/// [`entropy_warning`] for the threshold decision.
#[uniffi::export]
pub fn estimate_entropy(phrase: String) -> f64 {
    crate::seed::estimate_entropy(&phrase)
}

/// Non-blocking low-entropy warning for a phrase (specs/spec.md «Seed
/// policy», R-6): `Some(warning)` when the non-empty phrase's
/// [`estimate_entropy`] is below `MIN_ENTROPY_WARNING_BITS` (128),
/// `None` when the estimate is at or above the threshold **or** the
/// phrase is empty/whitespace-only (emptiness is a rejection, not a
/// warning — R-2). The UI surfaces `Some` as the «Low entropy»
/// dialog with Continue / Edit; the string is user-presentable as-is.
#[uniffi::export]
pub fn entropy_warning(phrase: String) -> Option<String> {
    crate::seed::entropy_warning(&phrase)
}

