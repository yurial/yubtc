    fn ms_create_address_ffi_rejects_bad_keys_and_quorums() {
        let h = ms_ffi_handle();
        let b0 = hex::encode(ms_ffi_pubkey(MS_FFI_SEED_B, 0));

        // Non-hex key: the R-MS-10 encoding refusal (the typed
        // MsError::InvalidKeyEncoding message verbatim through the
        // flat `Invalid` arm, like every other MsError).
        let err = h
            .ms_create_address(2, 1, vec!["zz-not-hex".to_string()], None, MsFormName::P2sh)
            .expect_err("non-hex key");
        assert!(matches!(err, YubtcError::Invalid(_)), "got: {err}");
        assert!(
            err.to_string().contains(
                "key encoding does not match the form: p2sh/p2wsh need 66-hex \
                 compressed keys, p2tr needs 64-hex x-only keys"
            ),
            "got: {err}"
        );

        // Wrong length (64 hex chars is the p2tr encoding, not the
        // compressed one p2sh expects).
        let err = h
            .ms_create_address(2, 1, vec!["ab".repeat(32)], None, MsFormName::P2sh)
            .expect_err("32-byte key");
        assert!(
            err.to_string()
                .contains("p2sh/p2wsh need 66-hex compressed keys"),
            "got: {err}"
        );

        // Uncompressed prefix.
        let mut raw = [0x04u8; 33];
        raw[32] = 0x09;
        let err = h
            .ms_create_address(2, 1, vec![hex::encode(raw)], None, MsFormName::P2sh)
            .expect_err("uncompressed key");
        assert!(
            err.to_string()
                .contains("p2sh/p2wsh need 66-hex compressed keys"),
            "got: {err}"
        );

        // Key count ≠ n.
        let err = h
            .ms_create_address(3, 2, vec![b0.clone()], None, MsFormName::P2sh)
            .expect_err("count mismatch");
        assert!(
            err.to_string()
                .contains("key count mismatch: expected exactly 3 keys, got 1"),
            "got: {err}"
        );

        // Quorum bounds (m = 0 and n = 16).
        let err = h
            .ms_create_address(2, 0, vec![b0.clone(), b0.clone()], None, MsFormName::P2sh)
            .expect_err("m = 0");
        assert!(
            err.to_string()
                .contains("quorum out of bounds: need 1 ≤ M ≤ N ≤ 15"),
            "got: {err}"
        );
        let sixteen: Vec<String> = (0..16)
            .map(|i| {
                let mut k = [0x02u8; 33];
                k[32] = i as u8 + 1;
                hex::encode(k)
            })
            .collect();
        let err = h
            .ms_create_address(16, 16, sixteen, None, MsFormName::P2sh)
            .expect_err("n = 16");
        assert!(
            err.to_string().contains("quorum out of bounds"),
            "got: {err}"
        );

        // Duplicate key.
        let err = h
            .ms_create_address(2, 1, vec![b0.clone(), b0], None, MsFormName::P2sh)
            .expect_err("duplicate");
        assert!(err.to_string().contains("duplicate key"), "got: {err}");
    }

    /// The x-only hex of a compressed fixture key — the p2tr `keys`
    /// grammar at the FFI boundary (R-MS-10, 64 chars).
    fn ms_ffi_xonly(key: &[u8; 33]) -> String {
        hex::encode(&key[1..33])
    }

