/// Map a reception-policy selection flag to the core policy enum
/// (specs/spec.md «Seed policy», R-1/R-3). Kept next to the FFI helpers so
/// the bool → enum mapping exists exactly once.
fn seed_policy(strict_bip39: bool) -> SeedPolicy {
    if strict_bip39 {
        SeedPolicy::StrictBip39
    } else {
        SeedPolicy::Permissive
    }
}

/// Validate a user-entered seed at reception under the selected
/// policy (specs/spec.md «Seed policy», R-2…R-5). Shared by the FFI
/// constructor and the test-only backend-injected constructor so both
/// enforce identical rules.
///
/// Contract: `seed` is the raw (already trimmed) user phrase.
/// `Ok(())` means reception may proceed; the empty phrase maps to
/// [`YubtcError::EmptySeed`] (R-2 keeps the bindings-level variant),
/// every other policy violation maps to [`YubtcError::Invalid`] with
/// the rule violation in the message. Never panics; performs no
/// I/O. In strict mode a violation must stop the caller BEFORE any
/// KDF work (R-4).
fn validate_reception(seed: &TSeed, strict_bip39: bool) -> Result<(), YubtcError> {
    crate::seed::validate_seed_with_policy(seed, seed_policy(strict_bip39)).map_err(|e| match e {
        crate::seed::SeedError::Empty => YubtcError::EmptySeed,
        other => YubtcError::Invalid(other.to_string()),
    })
}

// --- Runtime ---------------------------------------------------------

/// Process-wide tokio runtime used to block on async wallet calls.
///
/// `OnceLock` ensures a single instance: spawning a fresh runtime for
/// every FFI call would thrash the work-stealing scheduler and
/// disconnect `reqwest`'s keep-alive pool.
fn runtime() -> &'static tokio::runtime::Runtime {
    static RT: OnceLock<tokio::runtime::Runtime> = OnceLock::new();
    RT.get_or_init(|| {
        tokio::runtime::Builder::new_multi_thread()
            .enable_all()
            .thread_name("yubtc-uniffi")
            .build()
            .expect("yubtc: failed to build tokio runtime")
    })
}

/// Block the current thread until `fut` resolves. Convenience for the
/// FFI methods, which are all sync.
///
/// All calls go through the global [`runtime`]. FFI methods must be
/// invoked from a thread that is *not* inside a tokio runtime — that
/// is how Kotlin, Swift, and Python consume them today, and it keeps
/// the bridge predictable. Tests that need an async context use a
/// scoped [`runtime().block_on`] inside a plain `#[test]`.
fn block_on<F: std::future::Future>(fut: F) -> F::Output {
    runtime().block_on(fut)
}

// --- Error surface ---------------------------------------------------

/// Flat error type exposed across the FFI boundary.
///
/// Variants are spelled out so the foreign side can pattern-match by
/// name; the inner `String` carries the wallet- or net-level detail.
/// `From<WalletError>` and `From<NetError>` map every internal
/// failure to the most relevant variant.
#[derive(Debug, thiserror::Error, uniffi::Error)]
#[uniffi(flat_error)]
pub enum YubtcError {
    #[error("seed cannot be empty")]
    EmptySeed,

    #[error("privkey derivation failed: {0}")]
    PrivKey(String),

    #[error("address could not be decoded: {0}")]
    AddressDecode(String),

    #[error("transaction build failed: {0}")]
    TxBuild(String),

    #[error("transaction sign failed: {0}")]
    TxSign(String),

    #[error("psbt: {0}")]
    Psbt(String),

    #[error("network error: {0}")]
    Network(String),

    #[error("unsupported: {0}")]
    Unsupported(String),

    #[error("invalid argument: {0}")]
    Invalid(String),
}

impl From<wallet::WalletError> for YubtcError {
    fn from(e: wallet::WalletError) -> Self {
        match e {
            wallet::WalletError::EmptySeed => YubtcError::EmptySeed,
            wallet::WalletError::PrivKey(s) => YubtcError::PrivKey(s),
            wallet::WalletError::AddressDecode(s) => YubtcError::AddressDecode(s),
            wallet::WalletError::Network(s) => YubtcError::Network(s),
            wallet::WalletError::UnsupportedAddress(s) => YubtcError::Unsupported(s),
            wallet::WalletError::UnsupportedUtxoScript => {
                YubtcError::Unsupported("unsupported UTXO script".to_string())
            }
            other => YubtcError::TxBuild(other.to_string()),
        }
    }
}

impl From<net::NetError> for YubtcError {
    fn from(e: net::NetError) -> Self {
        match e {
            net::NetError::UnknownProvider(s) => {
                YubtcError::Invalid(format!("unknown provider: {s}"))
            }
            other => YubtcError::Network(other.to_string()),
        }
    }
}

impl From<crate::kdf::KdfError> for YubtcError {
    fn from(e: crate::kdf::KdfError) -> Self {
        YubtcError::PrivKey(e.to_string())
    }
}

impl From<crate::psbt::PsbtError> for YubtcError {
    fn from(e: crate::psbt::PsbtError) -> Self {
        YubtcError::Psbt(e.to_string())
    }
}

impl From<crate::address::AddressError> for YubtcError {
    fn from(e: crate::address::AddressError) -> Self {
        YubtcError::AddressDecode(e.to_string())
    }
}

impl From<crate::address::WifError> for YubtcError {
    fn from(e: crate::address::WifError) -> Self {
        YubtcError::Invalid(e.to_string())
    }
}

impl From<crate::misc::MiscError> for YubtcError {
    fn from(e: crate::misc::MiscError) -> Self {
        YubtcError::Invalid(e.to_string())
    }
}

impl From<crate::wallet::MsError> for YubtcError {
    fn from(e: crate::wallet::MsError) -> Self {
        // Like `TransactionError`: the multisig quorum surface has no
        // dedicated FFI variant — the flat `Invalid` arm carries the
        // typed message (`quorum out of bounds: …`, `WIF does not
        // match …`, ...) verbatim.
        YubtcError::Invalid(e.to_string())
    }
}

impl From<crate::wallet::MsSendError> for YubtcError {
    fn from(e: crate::wallet::MsSendError) -> Self {
        // Delegate each arm to its existing mapping so `ms send`
        // failures render exactly like the equivalent standalone
        // failure (MsError → Invalid, WalletError → per-variant,
        // PsbtError → Psbt, NetError → Network/Invalid).
        match e {
            crate::wallet::MsSendError::Ms(inner) => inner.into(),
            crate::wallet::MsSendError::Wallet(inner) => inner.into(),
            crate::wallet::MsSendError::Psbt(inner) => inner.into(),
            crate::wallet::MsSendError::Network(inner) => inner.into(),
        }
    }
}

